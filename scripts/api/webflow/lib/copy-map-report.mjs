// Summary numbers and the readable per-page copy map. Pure string building.
const STATUS_ORDER = ['change', 'same', 'second version listed', 'not on site', 'no copy yet', 'held']

export function summarise(map) {
  const rowsByStatus = Object.fromEntries(STATUS_ORDER.map((status) => [status, 0]))
  const rowsByDoc = {}
  for (const row of map.rows) {
    rowsByStatus[row.status] = (rowsByStatus[row.status] || 0) + 1
    if (row.doc) rowsByDoc[row.doc] = (rowsByDoc[row.doc] || 0) + 1
  }
  const sharedRows = map.rows.filter((row) => row.shared)
  const sharedTargets = new Set(sharedRows.filter((row) => row.status === 'change').map((row) => `${row.targetKind}|${row.page}|${row.target?.propertyId || row.target?.nodeId}`))
  return {
    rows: map.rows.length,
    rowsByStatus,
    rowsByDoc,
    sharedRows: sharedRows.length,
    sharedElementsNeedingDecision: sharedTargets.size,
    needsConfirmRows: map.rows.filter((row) => row.needsConfirm).length,
    conflictRows: map.rows.filter((row) => row.conflictsWith.length).length,
    duplicateRows: map.rows.filter((row) => row.duplicateOf).length,
    notes: map.notes.length,
    rooms: map.rooms && { matched: map.rooms.matched.length, docRoomsWithoutItem: map.rooms.docRoomsWithoutItem.length, itemsWithoutDoc: map.rooms.itemsWithoutDoc.length },
  }
}

const cell = (text, limit = 80) => {
  const flat = String(text ?? '').replace(/\s+/g, ' ').trim()
  return (flat.length > limit ? `${flat.slice(0, limit - 3)}...` : flat).replace(/\|/g, '\\|').replace(/\u2014/g, ' -- ')
}

function targetLabel(row) {
  const target = row.target
  if (row.targetKind === 'not-on-site') return 'not on site'
  if (row.status === 'held') return 'held'
  if (!target) return row.targetKind
  if (row.targetKind === 'cms-field') return `CMS ${row.cmsItem.collection} / ${row.cmsItem.name} / ${target.fieldSlug}`
  if (row.targetKind === 'component-prop') return `prop ${target.component} / ${target.property}${target.overridden === false ? ' (default)' : ''}`
  if (row.targetKind === 'component-fixed') return `fixed in ${target.component}${target.tag ? ` (${target.tag})` : ''}`
  return `page text${target.tag ? ` (${target.tag})` : ''}${target.section ? ` ${target.section.replace('section_', '')}` : ''}`
}

const flags = (row) => [
  row.shared ? `SHARED ${row.sharedPages.join(' ')}` : '',
  row.needsConfirm ? 'CONFIRM' : '',
  row.conflictsWith.length ? `CONFLICT ${row.conflictsWith.join(' ')}` : '',
  row.duplicateOf ? `duplicate of ${row.duplicateOf}` : '',
  row.joinedInto ? `joined into line ${row.joinedInto}` : '',
  row.scriptHeading ? 'script heading' : '',
].filter(Boolean).join('; ')

export function renderCopyMapMarkdown(output) {
  const { summary, rows, notes, rooms } = output
  const out = ['# Copy map', '', 'One row per doc line, matched to the staging element it replaces. Generated by `pnpm copy-map` from the committed docs and catalogue; machine-readable twin: `copy-map.json` (exact text; an em dash in a doc shows here as " -- ").', '']
  out.push('## Summary', '', '| status | rows |', '|---|---|', ...STATUS_ORDER.map((status) => `| ${status} | ${summary.rowsByStatus[status]} |`), '')
  out.push(`Rows: ${summary.rows}. Shared rows: ${summary.sharedRows} (${summary.sharedElementsNeedingDecision} elements need a decision). Rows to confirm: ${summary.needsConfirmRows}. Conflicting rows: ${summary.conflictRows}. Writer's notes recorded: ${summary.notes}.`, '')

  out.push('## Shared text needing a decision', '', 'These rows would change text that other pages show too (text fixed in a component, or a CMS template). Make it a prop or accept the shared change.', '')
  const sharedByElement = new Map()
  for (const row of rows.filter((candidate) => candidate.shared && candidate.status === 'change')) {
    const key = `${row.targetKind}|${row.page}|${row.target?.propertyId || row.target?.nodeId}`
    if (!sharedByElement.has(key)) sharedByElement.set(key, { row, count: 0 })
    sharedByElement.get(key).count++
  }
  for (const { row, count } of sharedByElement.values()) out.push(`- ${targetLabel(row)} on ${row.page}, now "${cell(row.currentText, 50)}", new "${cell(row.newText, 50)}" (${count} doc line${count > 1 ? 's' : ''}); also shown on: ${row.sharedPages.join(', ')}`)
  out.push('')

  out.push('## Second versions (deviations list for Omar)', '')
  for (const row of rows.filter((candidate) => candidate.alternates.length)) {
    out.push(`- ${row.doc} line ${row.line}: using "${cell(row.newText, 70)}"; also given: ${row.alternates.map((alternate) => `line ${alternate.line} "${cell(alternate.text, 70)}"${alternate.implicit ? ' (no "or" in doc)' : ''}`).join('; ')}`)
  }
  out.push('')

  if (rooms) {
    out.push('## Rooms', '', `Matched by name: ${rooms.matched.length}.`, '')
    out.push('Doc rooms with no room item (not created):', ...rooms.docRoomsWithoutItem.map((entry) => `- ${entry.docRoom} (line ${entry.line})${entry.possibleItems?.length ? `, possible item: ${entry.possibleItems.join(', ')}` : ''}`), '')
    out.push('Room items with no doc section (not deleted):', ...rooms.itemsWithoutDoc.map((entry) => `- ${entry.item}`), '')
  }

  out.push('## Held (C3)', '', ...rows.filter((row) => row.status === 'held').map((row) => `- ${row.page}: ${row.reason}`), '')

  out.push("## Writer's notes (never copy)", '', '| doc | line | note | kind |', '|---|---|---|---|', ...notes.map((note) => `| ${note.doc} | ${note.line} | ${cell(note.text)} | ${note.kind} |`), '')

  const groups = new Map()
  for (const row of rows) {
    const key = row.cmsItem ? `CMS ${row.cmsItem.collectionName} / ${row.cmsItem.name} (${row.page})` : row.page || `${row.doc} (no target page)`
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push(row)
  }
  out.push('## Rows by page', '')
  for (const [key, group] of [...groups].sort((a, b) => String(a[0]).localeCompare(String(b[0])))) {
    out.push(`### ${key}`, '', '| doc line | status | target | current | new | flags |', '|---|---|---|---|---|---|')
    for (const row of group) {
      const docLine = row.doc ? `${row.doc.replace('Guild-', '')}:${row.line ?? '-'}` : '-'
      out.push(`| ${docLine} | ${row.status} | ${cell(targetLabel(row), 60)} | ${cell(row.currentText, 50)} | ${cell(row.newText, 60)} | ${cell(flags(row) || row.reason || '', 90)} |`)
    }
    out.push('')
  }
  return out.join('\n')
}

#!/usr/bin/env node
// Where-used index: crawls every published staging page and records which pages carry each
// class family and each data attribute (and which src/utils module reads that attribute).
// Read-only, no credentials. Writes docs/reference/where-used.md and where-used.json.
// Usage: node scripts/api/webflow/where-used.mjs [baseUrl]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const OUT_MD = path.join(ROOT, 'docs/reference/where-used.md')
const OUT_JSON = path.join(ROOT, 'docs/reference/where-used.json')
const MAX_PAGES = 400

// Webflow runtime attributes and generic utility tokens say nothing about where a feature lives.
const IGNORED_ATTRIBUTES = /^data-(w-|wf-|node-type|ix|nav-menu-open|collapse|animation$|duration|easing|easing2|wait-ms|name$|redirect|aos)/

/** Class family of one class token: `venue-card_image` -> `venue-card`, `section_venue-card` -> `venue-card`. */
export const familyOf = (token) => {
  if (token.startsWith('w-') || !token.includes('_')) return null
  return token.startsWith('section_') ? token.slice('section_'.length) : token.split('_')[0]
}

/** Families and data-attribute names in one page's HTML. */
export const extract = (html) => {
  const families = new Set()
  const attributes = new Set()
  for (const [tag] of html.matchAll(/<[a-zA-Z][^>]*>/g)) {
    const classes = tag.match(/\sclass="([^"]*)"/)?.[1] ?? ''
    for (const token of classes.split(/\s+/)) {
      const family = token && familyOf(token)
      if (family) families.add(family)
    }
    for (const [, name] of tag.matchAll(/\s(data-[a-z0-9-]+)(?=[\s=>/])/g)) {
      if (!IGNORED_ATTRIBUTES.test(name)) attributes.add(name)
    }
  }
  return { families, attributes }
}

/** Same-origin page links in one page's HTML, as clean paths. */
export const linksOf = (html, base) => {
  const paths = new Set()
  for (const [, href] of html.matchAll(/\shref="([^"#?]*)[^"]*"/g)) {
    let url
    try { url = new URL(href, base) } catch { continue }
    if (url.origin !== new URL(base).origin) continue
    if (/\.[a-z0-9]{2,5}$/i.test(url.pathname)) continue // assets, not pages
    paths.add(url.pathname.replace(/\/$/, '') || '/')
  }
  return paths
}

/** Collapse CMS item pages (`/dining/zuma`) into `/dining/* (n)` so tables stay readable. */
export const summarise = (pages, allPages) => {
  if (pages.length === allPages.length) return `all ${allPages.length} pages`
  const groups = new Map()
  for (const page of pages) {
    const parts = page.split('/').filter(Boolean)
    const key = parts.length >= 2 ? `/${parts[0]}/*` : page
    groups.set(key, (groups.get(key) ?? 0) + 1)
  }
  return [...groups].map(([key, n]) => (key.endsWith('/*') ? `${key} (${n})` : key)).sort().join(', ')
}

const crawl = async (base) => {
  const seen = new Set(['/'])
  const queue = ['/']
  const pages = new Map()
  while (queue.length && pages.size < MAX_PAGES) {
    const batch = queue.splice(0, 6)
    await Promise.all(batch.map(async (page) => {
      const res = await fetch(base + page)
      if (!res.ok || !res.headers.get('content-type')?.includes('text/html')) return
      const html = await res.text()
      pages.set(page, extract(html))
      for (const link of linksOf(html, base)) {
        if (!seen.has(link)) { seen.add(link); queue.push(link) }
      }
    }))
  }
  return pages
}

const readersOf = (attribute) => {
  const dir = path.join(ROOT, 'src/utils')
  return fs.readdirSync(dir).filter((file) => file.endsWith('.ts') && fs.readFileSync(path.join(dir, file), 'utf8').includes(attribute))
    .map((file) => file.replace(/\.ts$/, ''))
}

const invert = (pages, key) => {
  const index = new Map()
  for (const [page, found] of pages) for (const name of found[key]) index.set(name, [...(index.get(name) ?? []), page])
  return new Map([...index].sort(([a], [b]) => a.localeCompare(b)))
}

const main = async () => {
  const base = (process.argv[2] ?? 'https://the-guild-hotel-c34e71.webflow.io').replace(/\/$/, '')
  const pages = await crawl(base)
  const allPages = [...pages.keys()].sort()
  const families = invert(pages, 'families')
  const attributes = invert(pages, 'attributes')

  fs.writeFileSync(OUT_JSON, JSON.stringify({
    base, generated: new Date().toISOString(), pages: allPages,
    families: Object.fromEntries([...families].map(([k, v]) => [k, v.sort()])),
    attributes: Object.fromEntries([...attributes].map(([k, v]) => [k, { pages: v.sort(), readBy: readersOf(k) }])),
  }, null, 1) + '\n')

  const md = [
    '# Where used',
    '',
    `Generated by \`pnpm where-used\` from ${base} on ${new Date().toISOString().slice(0, 10)}: ${allPages.length} pages. Do not edit by hand.`,
    '',
    'Before changing anything shared (a class family, a component, a data attribute, a module, a CMS list), look it up here, put every page listed in the plan, and check every one of them on staging before calling it done. Run `pnpm where-used` first: it reads the live staging site, so it is current. `/x/* (n)` means n CMS item pages under that template; check at least one.',
    '',
    '## Data attributes',
    '',
    '| Attribute | Read by | Pages |',
    '|---|---|---|',
    ...[...attributes].map(([name, list]) => `| \`${name}\` | ${readersOf(name).join(', ') || 'none'} | ${summarise(list, allPages)} |`),
    '',
    '## Class families',
    '',
    '| Family | Pages |',
    '|---|---|',
    ...[...families].map(([name, list]) => `| \`${name}\` | ${summarise(list, allPages)} |`),
    '',
  ].join('\n')
  fs.writeFileSync(OUT_MD, md)
  console.log(`${allPages.length} pages, ${families.size} families, ${attributes.size} attributes -> docs/reference/where-used.md`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()

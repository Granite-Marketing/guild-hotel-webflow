// Strip characters that must not reach generated markdown: em dashes (house
// rule), newlines, backticks and table pipes.
export const clean = (value) =>
  String(value ?? '')
    .replace(/\s*\u2014\s*/g, ', ')
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/`/g, "'")
    .replace(/\|/g, '/')
    .replace(/\s{2,}/g, ' ')
    .trim()

export const truncate = (value, max = 80) => {
  const text = clean(value)
  return text.length > max ? `${text.slice(0, max - 3).trimEnd()}...` : text
}

export const kebab = (value) => String(value ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

const normaliseName = (value) => String(value ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '')

export const humanize = (value) => {
  const text = clean(String(value ?? '').replace(/[-_]+/g, ' '))
  return text ? text.charAt(0).toUpperCase() + text.slice(1) : ''
}

const qid = (number) => `Q${String(number).padStart(3, '0')}`

// Merge vision review files ({sections:[{key,...}]}); later files (sorted by
// name) win per key.
export const mergeVision = (files) => {
  const map = new Map()
  for (const { data } of [...files].sort((a, b) => a.name.localeCompare(b.name))) {
    for (const record of data?.sections || []) {
      if (record && typeof record.key === 'string') map.set(record.key, { ...(map.get(record.key) || {}), ...record })
    }
  }
  return map
}

// Effective sections: inventory entries plus vision names and the vision
// slider rule. Inventory proposedName (which carries override names) wins.
export const effectiveSections = (inventory, { overrides = {}, vision = new Map() } = {}) => {
  const overrideSections = overrides.sections || {}
  return inventory.sections.map((entry) => {
    const review = vision.get(entry.key) || null
    const explicitName = entry.proposedName || null
    const visionName = review?.name ? clean(review.name) : null
    let { lane, laneReason } = entry
    if (review?.slider === true && overrideSections[entry.key]?.lane === undefined && lane !== 'manual') {
      lane = 'manual'
      laneReason = 'vision: slider'
    }
    const groupName = explicitName || visionName
    const displayName = clean(explicitName || (visionName ? humanize(visionName) : null) || humanize(entry.firstHeading || entry.slug) || entry.key)
    return { ...entry, lane, laneReason, vision: review, groupName, displayName }
  })
}

class UnionFind {
  constructor () { this.parent = new Map() }
  find (key) {
    if (!this.parent.has(key)) this.parent.set(key, key)
    let root = key
    while (this.parent.get(root) !== root) root = this.parent.get(root)
    this.parent.set(key, root)
    return root
  }
  union (a, b) {
    const rootA = this.find(a)
    const rootB = this.find(b)
    if (rootA !== rootB) this.parent.set(rootB < rootA ? rootA : rootB, rootB < rootA ? rootB : rootA)
  }
}

const mostCommon = (values) => {
  const counts = new Map()
  for (const value of values) if (value) counts.set(value, (counts.get(value) || 0) + 1)
  let best = null
  for (const [value, count] of counts) if (best === null || count > counts.get(best)) best = value
  return best
}

const manualCategory = (section) => {
  if (section.lane === 'needs-decision') return 'decision'
  const reason = String(section.laneReason || '')
  if (section.pageSlug === 'nav-elements' || /\bnav\b/i.test(reason)) return 'navbar'
  if (/slider|carousel|gallery/i.test(reason)) return 'slider'
  if (section.source === 'side' || /overlay|modal/i.test(reason)) return 'overlay'
  return 'other'
}

const MANUAL_ENTRIES = [
  ['navbar', 'Navbar and menu', 'Build the navbar component and its menu states by hand. Agent sections exclude every nav instance (see each brief). Add the component to `docs/reference/style-inventory.md` once it exists.'],
  ['overlay', 'Modals and overlays', 'Build each overlay as a dialog following `docs/reference/modal-setup.md`.'],
  ['slider', 'Sliders and galleries', 'Build sliders with Swiper per `docs/reference/swiper-slider-setup.md`.'],
  ['decision', 'Needs a lane decision', 'Decide each item: set `lane` in `figma/inventory.overrides.json`, re-run `pnpm figma:inventory` and `pnpm figma:queue`.'],
  ['other', 'Other manual sections', 'Marked manual by an override or review; build by hand.']
]

// Plan the queue from effective sections and the inventory.
export const planQueue = (inventory, sections, { fonts = [] } = {}) => {
  const pages = inventory.pages
  const pageBySlug = new Map(pages.map((page) => [page.pageSlug, page]))
  const unitOf = (pageSlug) => pageBySlug.get(pageSlug)?.cmsTemplateGroup || pageSlug
  const cmsPages = new Set(pages.filter((page) => page.cmsTemplateGroup).map((page) => page.pageSlug))
  const pageSectionCount = (page) => sections.filter((section) => section.pageSlug === page.pageSlug && section.source === 'page').length

  // Page build order: home, then collection pages, then the rest (inventory order).
  const ordered = pages.filter((page) => !cmsPages.has(page.pageSlug))
  const pageOrder = [
    ...ordered.filter((page) => page.pageSlug === 'home'),
    ...ordered.filter((page) => page.pageSlug !== 'home' && page.isCollectionPage),
    ...ordered.filter((page) => page.pageSlug !== 'home' && !page.isCollectionPage)
  ].map((page) => page.pageSlug)
  const rank = (section) => {
    const position = pageOrder.indexOf(section.pageSlug)
    return [position === -1 ? pageOrder.length + pages.findIndex((page) => page.pageSlug === section.pageSlug) : position, section.index ?? Infinity]
  }
  const byRank = (a, b) => {
    const [pageA, indexA] = rank(a)
    const [pageB, indexB] = rank(b)
    return pageA - pageB || indexA - indexB || a.key.localeCompare(b.key)
  }

  const agent = sections.filter((section) => section.lane === 'agent')
  const agentKeys = new Set(agent.map((section) => section.key))

  // Shared groups: union by exact cluster, by explicit or vision name, and by mergeWith.
  const union = new UnionFind()
  const firstBy = new Map()
  for (const section of agent) {
    union.find(section.key)
    for (const tag of [section.clusterId && `c:${section.clusterId}`, section.groupName && `n:${normaliseName(section.groupName)}`]) {
      if (!tag || tag === 'n:') continue
      if (firstBy.has(tag)) union.union(firstBy.get(tag), section.key)
      else firstBy.set(tag, section.key)
    }
    if (section.mergeWith && agentKeys.has(section.mergeWith)) union.union(section.mergeWith, section.key)
  }
  const groups = new Map()
  for (const section of agent) {
    const root = union.find(section.key)
    if (!groups.has(root)) groups.set(root, [])
    groups.get(root).push(section)
  }
  const shared = []
  const assigned = new Map()
  for (const members of groups.values()) {
    const units = new Set(members.map((member) => unitOf(member.pageSlug)))
    if (units.size < 2) continue
    members.sort(byRank)
    const pagesUsing = [...new Set(members.map((member) => member.pageSlug))]
    const reference = members.find((member) => !cmsPages.has(member.pageSlug)) || members[0]
    const title = mostCommon(members.map((member) => member.groupName && member.displayName)) || reference.displayName
    shared.push({ members, pages: pagesUsing, units: [...units], reference, title })
  }
  shared.sort((a, b) => b.pages.length - a.pages.length || b.units.length - a.units.length || byRank(a.members[0], b.members[0]))

  const entries = []
  const add = (entry) => {
    entry.id = qid(entries.length + 1)
    entries.push(entry)
    return entry
  }
  const tokenSync = add({ type: 'setup', kind: 'tokens', lane: 'agent (approval)', title: 'Token sync: variables and Relume classes', slug: 'token-sync', dependsOn: [], sections: [] })
  const fontUpload = add({ type: 'setup', kind: 'fonts', lane: 'manual', title: `Font upload: ${fonts.join(', ') || 'none required'}`, slug: 'font-upload', dependsOn: [], sections: [] })
  const assetUpload = add({ type: 'setup', kind: 'assets', lane: 'agent (approval)', title: 'Asset upload to the Webflow library', slug: 'asset-upload', dependsOn: [], sections: [] })
  const pageCreate = add({
    type: 'setup',
    kind: 'pages',
    lane: 'agent (approval)',
    title: 'Create Webflow pages for each Figma page',
    slug: 'create-pages',
    dependsOn: [],
    sections: [],
    pageList: pages.filter((page) => pageSectionCount(page) > 0).map((page) => page.pageSlug)
  })
  const setupIds = [tokenSync.id, fontUpload.id, assetUpload.id, pageCreate.id]

  // Manual entries for Stephen.
  const manualSections = sections.filter((section) => section.lane !== 'agent')
  for (const [category, title, instruction] of MANUAL_ENTRIES) {
    const members = manualSections.filter((section) => manualCategory(section) === category)
    if (!members.length) continue
    const entry = add({ type: 'manual', kind: category, lane: 'manual', title, slug: kebab(title), dependsOn: [tokenSync.id, fontUpload.id], sections: members, instruction })
    for (const member of members) assigned.set(member.key, entry.id)
  }

  const sharedEntryOf = new Map()
  for (const group of shared) {
    const entry = add({
      type: 'shared',
      lane: 'agent',
      title: `Shared: ${group.title}`,
      slug: `shared-${kebab(group.title).slice(0, 40)}`,
      dependsOn: [...setupIds],
      sections: group.members,
      pages: group.pages,
      reference: group.reference
    })
    for (const member of group.members) {
      assigned.set(member.key, entry.id)
      sharedEntryOf.set(member.key, entry)
    }
  }
  const sharedUsedBy = (pageSlugs) => [...new Set(sections.filter((section) => pageSlugs.includes(section.pageSlug) && sharedEntryOf.has(section.key)).map((section) => sharedEntryOf.get(section.key).id))]
    .sort()

  const cmsEntryOf = new Map()
  for (const group of inventory.cmsGroups || []) {
    const groupPages = [group.referencePage, ...group.pages.filter((slug) => slug !== group.referencePage)]
    const members = agent
      .filter((section) => groupPages.includes(section.pageSlug) && !assigned.has(section.key))
      .sort((a, b) => groupPages.indexOf(a.pageSlug) - groupPages.indexOf(b.pageSlug) || (a.index ?? Infinity) - (b.index ?? Infinity) || a.key.localeCompare(b.key))
    const entry = add({
      type: 'cms',
      lane: 'agent (collection needs approval)',
      title: `CMS template: ${group.id} (${groupPages.join(', ')})`,
      slug: `cms-${kebab(group.id.replace(/^cms-/, ''))}`,
      dependsOn: [...setupIds, ...sharedUsedBy(groupPages)],
      sections: members,
      pages: groupPages,
      group
    })
    for (const member of members) assigned.set(member.key, entry.id)
    cmsEntryOf.set(group.id, entry)
  }

  for (const pageSlug of pageOrder) {
    const page = pageBySlug.get(pageSlug)
    const remaining = agent.filter((section) => section.pageSlug === pageSlug && !assigned.has(section.key)).sort(byRank)
    const sharedIds = sharedUsedBy([pageSlug])
    if (!remaining.length && !sharedIds.length) continue
    const listing = (inventory.collectionPages || []).find((entry) => entry.pageSlug === pageSlug)
    const cmsDeps = listing?.listsGroup && cmsEntryOf.has(listing.listsGroup) ? [cmsEntryOf.get(listing.listsGroup).id] : []
    const entry = add({
      type: 'page',
      lane: 'agent',
      title: `Page: ${humanize(pageSlug)}`,
      slug: `page-${pageSlug}`,
      dependsOn: [...setupIds, ...sharedIds, ...cmsDeps],
      sections: remaining,
      pages: [pageSlug],
      page,
      listing: listing || null,
      sharedOnPage: sections.filter((section) => section.pageSlug === pageSlug && sharedEntryOf.has(section.key)).sort(byRank),
      manualOnPage: sections.filter((section) => section.pageSlug === pageSlug && section.lane !== 'agent').sort(byRank)
    })
    for (const member of remaining) assigned.set(member.key, entry.id)
  }

  // Coverage check.
  const counts = new Map()
  for (const entry of entries) for (const section of entry.sections) counts.set(section.key, (counts.get(section.key) || 0) + 1)
  const unplaced = agent.filter((section) => !counts.has(section.key)).map((section) => section.key)
  const duplicated = [...counts].filter(([, count]) => count > 1).map(([key]) => key)
  return { entries, unplaced, duplicated, agentCount: agent.length, assigned, pageOrder }
}

// Asset index: image fills from specs plus brand SVGs and vectors.
export const buildAssetIndex = ({ sections, specs, manifest, existing, brandFiles = [], vectors = null, sectionRanges = [] }) => {
  const manifestByRef = new Map()
  for (const asset of manifest?.assets || []) if (asset.figmaImageRef) manifestByRef.set(asset.figmaImageRef, asset)
  const usedBy = new Map()
  for (const section of sections) {
    const spec = specs.get(section.key)
    for (const image of spec?.images || []) {
      if (!image.imageRef) continue
      if (!usedBy.has(image.imageRef)) usedBy.set(image.imageRef, new Set())
      usedBy.get(image.imageRef).add(section.key)
    }
  }
  const images = {}
  for (const ref of [...usedBy.keys()].sort()) {
    const fromManifest = manifestByRef.get(ref)
    const before = existing?.images?.[ref] || {}
    images[ref] = {
      file: fromManifest?.localPath ?? before.file ?? null,
      width: fromManifest?.dimensions?.width ?? before.width ?? null,
      height: fromManifest?.dimensions?.height ?? before.height ?? null,
      usedBy: [...usedBy.get(ref)].sort(),
      webflowAssetId: before.webflowAssetId ?? fromManifest?.webflowAssetId ?? null,
      webflowUrl: before.webflowUrl ?? fromManifest?.webflowUrl ?? null
    }
  }
  const brand = {}
  for (const file of [...brandFiles].sort()) {
    const name = file.replace(/^.*\//, '').replace(/\.svg$/, '')
    const before = existing?.brand?.[name] || {}
    brand[name] = { file, webflowAssetId: before.webflowAssetId ?? null, webflowUrl: before.webflowUrl ?? null }
  }
  const result = {
    version: 1,
    _readme: 'Generated by scripts/api/figma/build-queue.mjs. images: Figma imageRef to local file and the sections using it. brand and vectors: committed SVGs. webflowAssetId and webflowUrl are filled after an approved upload (pnpm run upload-assets) and preserved on re-run.',
    images,
    brand
  }
  if (vectors) {
    const previous = new Map((existing?.vectors || []).map((vector) => [vector.id, vector]))
    result.vectors = (vectors.vectors || [])
      .map((vector) => {
        const keys = new Set()
        let unmatched = 0
        let inManualOverlay = 0
        for (const use of vector.uses || []) {
          const range = rangeForUse(use, sectionRanges)
          if (!range) unmatched++
          else if (insideOverlay(use, range)) inManualOverlay++
          else keys.add(range.key)
        }
        const before = previous.get(vector.id) || {}
        return {
          file: vector.file ?? null,
          id: vector.id,
          name: clean(vector.name),
          width: vector.width ?? null,
          height: vector.height ?? null,
          type: vector.type ?? null,
          useCount: (vector.uses || []).length,
          unmatchedUses: unmatched,
          manualOverlayUses: inManualOverlay,
          usedBy: [...keys].sort(),
          webflowAssetId: before.webflowAssetId ?? null,
          webflowUrl: before.webflowUrl ?? null
        }
      })
      .sort((a, b) => String(a.file ?? '').localeCompare(String(b.file ?? '')) || String(a.id).localeCompare(String(b.id)))
  }
  return result
}

// Section ranges per frame: half-open [cropY0, cropY1), last one closed.
export const rangeForUse = (use, ranges) => {
  const centre = use.y + (use.height || 0) / 2
  for (const range of ranges) {
    if (range.frameId !== use.frameId) continue
    if (centre >= range.y0 && (centre < range.y1 || (range.last && centre <= range.y1))) return range
  }
  return null
}

export const sectionForUse = (use, ranges) => rangeForUse(use, ranges)?.key ?? null

// A use whose centre sits inside one of the section's manual overlays (for
// example the navbar) belongs to that hand-built overlay, not the section.
// Overlay boxes are relative to the crop top (spec bboxOrigin).
const insideOverlay = (use, range) => {
  const centreX = use.x + (use.width || 0) / 2
  const centreY = use.y + (use.height || 0) / 2 - range.y0
  return (range.overlays || []).some((box) => centreX >= box.x && centreX <= box.x + box.width && centreY >= box.y && centreY <= box.y + box.height)
}

// Token lookups for one entry's specs.
export const tokenSummary = (specList, tokens) => {
  if (!tokens?.mapping) return { typography: [], colors: [], fontVariables: [] }
  const byNamed = new Map()
  const byKey = new Map()
  for (const mapping of tokens.mapping.typography || []) {
    if (mapping.source?.type === 'namedStyle') byNamed.set(mapping.source.id, mapping)
    else if (mapping.source?.key) byKey.set(mapping.source.key, mapping)
  }
  const colorByMember = new Map()
  for (const mapping of tokens.mapping.colors || []) for (const member of mapping.members || [mapping.key]) colorByMember.set(member, mapping)
  const typography = new Map()
  const colors = new Map()
  for (const spec of specList) {
    for (const text of spec?.texts || []) {
      const key = [text.fontFamily, text.fontWeight, text.fontSize, text.lineHeightPx, text.letterSpacing, text.textCase || 'ORIGINAL'].join('|')
      const mapping = (text.styleId && byNamed.get(text.styleId)) || byKey.get(key)
      const label = mapping
        ? `${clean(mapping.source.name || mapping.source.key)} -> \`${mapping.target}\`${mapping.weightClass ? ` + \`${mapping.weightClass}\`` : ''}${mapping.suggestedComboClass ? ` (combo \`${mapping.suggestedComboClass}\`)` : ''}`
        : `${clean(text.fontFamily)} ${text.fontSize}/${text.lineHeightPx}: unmapped, check \`figma/tokens.json\` textStyles`
      typography.set(label, (typography.get(label) || 0) + 1)
    }
    for (const color of spec?.colors || []) {
      const member = `${color.hex}@${color.opacity}`
      const mapping = colorByMember.get(member)
      const label = mapping?.target ? `${color.hex} -> \`${mapping.target}\`` : `${color.hex}${color.opacity !== 1 ? ` at ${color.opacity}` : ''}: no variable${mapping?.role ? ` (${mapping.role})` : ''}`
      colors.set(label, (colors.get(label) || 0) + (color.count || 1))
    }
  }
  const sorted = (map) => [...map].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([label]) => label)
  return {
    typography: sorted(typography),
    colors: sorted(colors),
    fontVariables: (tokens.mapping.fontVariables || []).map((entry) => `\`${entry.variable}\`: ${clean(entry.value)}`)
  }
}

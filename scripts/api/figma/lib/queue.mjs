// Strip characters that must not reach generated markdown: em dashes (house
// rule), newlines, backticks and table pipes.
export const clean = (value) =>
  String(value ?? '')
    .replace(/\s*\u2014\s*/g, ', ')
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/`/g, "'")
    .replace(/\|/g, '/')
    .replace(/\s{2,}/g, ' ')
    .trim()

export const truncate = (value, max = 80) => {
  const text = clean(value)
  return text.length > max ? `${text.slice(0, max - 3).trimEnd()}...` : text
}

export const kebab = (value) => String(value ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

const normaliseName = (value) => String(value ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '')

export const humanize = (value) => {
  const text = clean(String(value ?? '').replace(/[-_]+/g, ' '))
  return text ? text.charAt(0).toUpperCase() + text.slice(1) : ''
}

const qid = (number) => `Q${String(number).padStart(3, '0')}`

// Merge vision review files ({sections:[{key,...}]}); later files (sorted by
// name) win per key.
export const mergeVision = (files) => {
  const map = new Map()
  for (const { data } of [...files].sort((a, b) => a.name.localeCompare(b.name))) {
    for (const record of data?.sections || []) {
      if (record && typeof record.key === 'string') map.set(record.key, { ...(map.get(record.key) || {}), ...record })
    }
  }
  return map
}

// Effective sections: inventory entries plus vision names and the vision
// slider rule. Inventory proposedName (which carries override names) wins.
export const effectiveSections = (inventory, { overrides = {}, vision = new Map() } = {}) => {
  const overrideSections = overrides.sections || {}
  return inventory.sections.map((entry) => {
    const review = vision.get(entry.key) || null
    const explicitName = entry.proposedName || null
    const visionName = review?.name ? clean(review.name) : null
    let { lane, laneReason } = entry
    if (review?.slider === true && overrideSections[entry.key]?.lane === undefined && lane !== 'manual') {
      lane = 'manual'
      laneReason = 'vision: slider'
    }
    const groupName = explicitName || visionName
    const displayName = clean(explicitName || (visionName ? humanize(visionName) : null) || humanize(entry.firstHeading || entry.slug) || entry.key)
    return { ...entry, lane, laneReason, vision: review, groupName, displayName }
  })
}

class UnionFind {
  constructor () { this.parent = new Map() }
  find (key) {
    if (!this.parent.has(key)) this.parent.set(key, key)
    let root = key
    while (this.parent.get(root) !== root) root = this.parent.get(root)
    this.parent.set(key, root)
    return root
  }
  union (a, b) {
    const rootA = this.find(a)
    const rootB = this.find(b)
    if (rootA !== rootB) this.parent.set(rootB < rootA ? rootA : rootB, rootB < rootA ? rootB : rootA)
  }
}

const mostCommon = (values) => {
  const counts = new Map()
  for (const value of values) if (value) counts.set(value, (counts.get(value) || 0) + 1)
  let best = null
  for (const [value, count] of counts) if (best === null || count > counts.get(best)) best = value
  return best
}

// Manual category: the vision kind first, then the inventory lane reason.
const manualCategory = (section) => {
  if (section.lane === 'needs-decision') return 'decision'
  const kind = section.vision?.kind
  if (kind === 'nav') return 'navbar'
  if (kind === 'overlay') return 'overlay'
  if (section.vision?.slider === true || kind === 'slider') return 'slider'
  const reason = String(section.laneReason || '')
  if (section.pageSlug === 'nav-elements' || /\bnav\b/i.test(reason)) return 'navbar'
  if (/slider|carousel|gallery/i.test(reason)) return 'slider'
  if (section.source === 'side' || /overlay|modal/i.test(reason)) return 'overlay'
  return 'other'
}


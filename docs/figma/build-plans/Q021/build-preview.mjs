// Generates preview.css and preview.html for Q021 from plan.json, so the preview
// uses only the plan's classes and style values. Run from the repo root:
//   node docs/figma/build-plans/Q021/build-preview.mjs
import fs from 'node:fs'
import path from 'node:path'

const dir = 'docs/figma/build-plans/Q021'
const plan = JSON.parse(fs.readFileSync(path.join(dir, 'plan.json'), 'utf8'))
const toRoot = '../../../../'

// ---------- CSS ----------
const media = {
  desktop: null,
  tablet: '(max-width: 991px)',
  mobileLandscape: '(max-width: 767px)',
  mobilePortrait: '(max-width: 479px)',
}
const rules = Object.fromEntries(Object.keys(media).map((bp) => [bp, []]))
const decls = (styles) =>
  Object.entries(styles)
    .map(([prop, value]) => `  ${prop}: ${value.replace(/url\("([^"]+)"\)/, (_, file) => `url("${file}")`)};`)
    .join('\n')
const addRule = (selector, byBreakpoint) => {
  for (const [bp, styles] of Object.entries(byBreakpoint ?? {})) {
    if (styles && Object.keys(styles).length) rules[bp].push(`${selector} {\n${decls(styles)}\n}`)
  }
}

for (const c of plan.reusedClassAssumptions) addRule(c.comboOn ? `.${c.comboOn}.${c.name}` : `.${c.name}`, c.styles)
for (const c of plan.proposedShared) addRule(c.comboOn ? `.${c.comboOn}.${c.name}` : `.${c.name}`, c.styles)
for (const c of plan.familyClasses) addRule(`.${c.name}`, c.styles)
for (const v of plan.variants) addRule(`.${v.on}.${v.modifier}`, v.styleDeltas)

const css = [
  '/* Generated by build-preview.mjs from plan.json. Do not edit by hand. */',
  '',
  '/* Preview shim (not part of the plan): variable values from figma/tokens.json and D01,',
  '   font fallbacks because the brand fonts are not available locally, and element resets',
  '   that the Relume global styles provide in Webflow. Sackers Heavy Gothic is an all-caps',
  '   face, so the fallback is uppercased to keep line lengths comparable. */',
  ':root {',
  '  --color-neutral-100: #f4efdf;',
  '  --color-neutral-300: #d1d1d1;',
  '  --color-neutral-900: #262118;',
  '  --color-accent: #29310c;',
  '  --color-brand-4a1217: #4a1217;',
  '  --font-style-heading: "Sackers Heavy Gothic", Copperplate, "Copperplate Gothic", serif;',
  '  --font-style-body: "Gatch Test", "Avenir Next", Futura, sans-serif;',
  '}',
  '*, *::before, *::after { box-sizing: border-box; }',
  'body { margin: 0; background: var(--color-neutral-100); font-family: var(--font-style-body); }',
  'h1, h2, h3, h4, p, figure { margin: 0; }',
  '.heading-style-display, .heading-style-h1, .heading-style-h2, .heading-style-h3, .heading-style-h4, .button, .text-style-eyebrow-caps { text-transform: uppercase; }',
  '.preview-label { font: 12px/1 ui-monospace, monospace; padding: 8px 12px; background: #222; color: #fff; }',
  '',
  '/* Plan styles */',
  ...rules.desktop,
  ...Object.entries(media)
    .filter(([bp]) => bp !== 'desktop')
    .map(([bp, query]) => `@media ${query} {\n${rules[bp].map((r) => r.replace(/^/gm, '  ')).join('\n')}\n}`),
  '',
].join('\n')

// ---------- HTML ----------
const byKey = Object.fromEntries(plan.instances.map((i) => [i.section, i]))
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')

// Each preview renders one crop. items: the instances shown as panels (first is on top).
const previews = [
  { slug: 'base', title: 'base (home/05)', root: 'home/05-dress-up-for-the-rich-worldly', modifier: null, items: ['home/05-dress-up-for-the-rich-worldly'] },
  { slug: 'media-center', title: 'is-media-center, snap start state (home/04)', root: 'home/04-an-unexpected-resort-dining-experience', modifier: 'is-media-center', startState: true, snap: true, items: ['home/04-an-unexpected-resort-dining-experience'] },
  { slug: 'tall', title: 'is-tall, brief is-2-images + is-tall (home/11)', root: 'home/11-rooms-suites', modifier: 'is-tall', items: ['home/11-rooms-suites'] },
  { slug: 'left', title: 'is-left (home/15)', root: 'home/15-meetings-events', modifier: 'is-left', items: ['home/15-meetings-events'] },
  { slug: 'media-center-tabs', title: 'is-media-center plus tabs, brief is-left + is-media-center (dining-collection/03)', root: 'dining-collection/03-zuma', modifier: 'is-media-center', startState: true, snap: true, items: ['dining-collection/03-zuma'] },
  { slug: 'no-image', title: 'base without image, brief is-cream + is-no-image (meetings-collection/03)', root: 'meetings-collection/03-council-boardroom', modifier: null, items: ['meetings-collection/03-council-boardroom'] },
]

const modifiedElements = (modifier) => new Set(plan.variants.filter((v) => v.modifier === modifier).map((v) => v.on))

function render(node, ctx, depth) {
  const pad = '  '.repeat(depth)
  const content = ctx.item?.content ?? {}
  const itemClasses = ctx.item?.classes ?? {}
  if (node.repeat === 'items') return ctx.items.map((item) => render({ ...node, repeat: undefined }, { ...ctx, item }, depth)).join('\n')
  if (node.repeat === 'tabs') return (ctx.root.content.tabs ?? []).map((label, index) => render({ ...node, repeat: undefined, prop: undefined, text: label, active: index === 0 }, ctx, depth)).join('\n')
  if (node.repeat === 'list') return (content.list ?? []).map((label, index) => render({ ...node, repeat: undefined, active: index === 0, label }, ctx, depth)).join('\n')

  // optional elements disappear without content
  const has = {
    intro: !!ctx.root.content.introHeading,
    tabs: !!ctx.root.content.tabs,
    figure: !!content.image,
    header: !!(content.heading || content.logo || content.text),
    'logo-wrapper': !!content.logo,
    text: !!content.text,
    footer: !!content.button,
    list: !!content.list,
  }
  if (node.optional && node.element && has[node.element] === false) return ''
  if (node.optional && node.prop === 'heading' && !content.heading) return ''

  let classes = [...node.classes]
  if (node.prop === 'heading' && itemClasses.heading) classes = [itemClasses.heading]
  if (node.element === 'text' && itemClasses.text) classes = ['venue-card-fullbleed_text', itemClasses.text]
  if (node.prop === 'button' && itemClasses.button) classes = itemClasses.button.split(' ')
  if (ctx.modifier && classes[0] && ctx.modified.has(classes[0])) classes.push(ctx.modifier)
  if (node.active && (classes[0] === 'venue-card-fullbleed_tab' || classes[0] === 'venue-card-fullbleed_list-link')) classes.push('is-active')

  const attrs = []
  if (classes.length) attrs.push(`class="${classes.join(' ')}"`)
  for (const [key, value] of Object.entries(node.attributes ?? {})) {
    if (key.startsWith('data-scroll-enlarge-snap') && !ctx.snap) continue
    if (key === 'data-scroll-enlarge-snap') continue // root attribute is set per group below
    attrs.push(value && !value.startsWith('(') ? `${key}="${esc(value)}"` : key === 'aria-label' ? `${key}="Venues"` : key)
  }
  if (node.element === 'root' && ctx.snap) attrs.push('data-scroll-enlarge-snap')
  if (node.prop === 'image') attrs.push(`src="${toRoot}${content.image.local}"`, `alt=""`)
  if (node.prop === 'logo') attrs.push(`src="${toRoot}${content.logo.svg}"`, `alt="${esc(content.logo.alt)}"`)
  if (node.prop === 'heading') node = { ...node, tag: ctx.snap ? 'h3' : 'h2' }

  const open = `<${node.tag}${attrs.length ? ' ' + attrs.join(' ') : ''}>`
  if (node.tag === 'img') return pad + open
  let inner = ''
  if (node.prop === 'introHeading') inner = esc(ctx.root.content.introHeading)
  else if (node.prop === 'heading') inner = esc(content.heading)
  else if (node.prop === 'text') inner = esc(content.text)
  else if (node.prop === 'button') inner = esc(content.button)
  else if (node.prop === 'listLabel') inner = esc(ctx.label)
  else if (node.text) inner = esc(node.text)
  if (node.label) ctx = { ...ctx, label: node.label }
  if (inner) return `${pad}${open}${inner}</${node.tag}>`
  const children = (node.children ?? []).map((child) => render(child, ctx, depth + 1)).filter(Boolean)
  return children.length ? `${pad}${open}\n${children.join('\n')}\n${pad}</${node.tag}>` : `${pad}${open}</${node.tag}>`
}

const blocks = previews.map((p) => {
  const root = byKey[p.root]
  const items = p.items.map((key) => byKey[key])
  const ctx = { root, items, modifier: p.modifier, modified: modifiedElements(p.modifier), snap: !!p.snap }
  return `<div id="variant-${p.slug}">\n<div class="preview-label">${esc(p.title)}</div>\n${render(plan.tree[0], ctx, 0)}\n</div>`
})

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Q021 venue-card-fullbleed preview</title>
<link rel="stylesheet" href="preview.css">
</head>
<body>
<!-- Generated by build-preview.mjs from plan.json. Static: scrollEnlargeSnap is not loaded, so snap previews show the start state. -->
${blocks.join('\n\n')}
</body>
</html>
`

fs.writeFileSync(path.join(dir, 'preview.css'), css)
fs.writeFileSync(path.join(dir, 'preview.html'), html)
console.log('wrote preview.css and preview.html with', previews.length, 'variants')
export const variantSlugs = previews.map((p) => p.slug)

// Generates preview.css and preview.html from plan.json, so the preview only
// uses the plan's classes and style values. Run: node docs/figma/build-plans/Q025/render-preview.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const planDirectory = dirname(fileURLToPath(import.meta.url))
const plan = JSON.parse(readFileSync(join(planDirectory, 'plan.json'), 'utf8'))

const breakpointQueries = {
  desktop: null,
  tablet: '(max-width: 991px)',
  mobileLandscape: '(max-width: 767px)',
  mobilePortrait: '(max-width: 479px)',
}

const rulesByBreakpoint = Object.fromEntries(Object.keys(breakpointQueries).map((name) => [name, []]))

const addRules = (selector, stylesByBreakpoint) => {
  for (const [breakpoint, declarations] of Object.entries(stylesByBreakpoint ?? {})) {
    const entries = Object.entries(declarations ?? {})
    if (entries.length === 0) continue
    const body = entries.map(([property, value]) => `  ${property}: ${value};`).join('\n')
    rulesByBreakpoint[breakpoint].push(`${selector} {\n${body}\n}`)
  }
}

for (const [className, styles] of Object.entries(plan.reusedStyles)) {
  if (className.startsWith('_')) continue
  addRules(`.${className}`, styles)
}
for (const shared of plan.proposedShared) addRules(`.${shared.name}`, shared.styles)
for (const family of plan.familyClasses) addRules(`.${family.name}`, family.styles)
for (const variant of plan.variants) addRules(`.${variant.on}.${variant.modifier}`, variant.styleDeltas)

const variableDeclarations = Object.entries(plan.variableValues)
  .filter(([name]) => !name.startsWith('_'))
  .map(([name, value]) => `  --${name}: ${value};`)
  .join('\n')

const cssSections = [
  '/* Generated by render-preview.mjs from plan.json. Do not edit by hand. */',
  `:root {\n${variableDeclarations}\n}`,
  '*, *::before, *::after { box-sizing: border-box; }\nbody { margin: 0; font-family: var(--font-style-body); color: var(--color-accent); }\nh2, h3, p { margin: 0; font-weight: 400; }\n.preview-label { font: 12px/1.4 monospace; padding: 0.5rem 1rem; background: #222; color: #eee; margin: 0; }',
]
for (const [breakpoint, query] of Object.entries(breakpointQueries)) {
  const rules = rulesByBreakpoint[breakpoint].join('\n\n')
  if (!rules) continue
  cssSections.push(query ? `@media ${query} {\n${rules.replace(/^/gm, '  ')}\n}` : rules)
}
writeFileSync(join(planDirectory, 'preview.css'), `${cssSections.join('\n\n')}\n`)

const familyModifierTargets = new Map()
for (const variant of plan.variants) {
  const targets = familyModifierTargets.get(variant.modifier) ?? new Set()
  targets.add(variant.on)
  familyModifierTargets.set(variant.modifier, targets)
}

const escapeHtml = (value) =>
  String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

const isEmpty = (value) => value === undefined || value === null || value === '' || value === false

const renderNode = (node, content, modifiers, depth) => {
  if (node.optional && isEmpty(content[node.optional])) return ''
  if (node.repeat) {
    return (content[node.repeat] ?? [])
      .map((itemContent) => renderNode({ ...node, repeat: undefined }, itemContent, modifiers, depth))
      .join('')
  }
  let classes = [...node.classes]
  if (node.headingClassProp && content[node.headingClassProp]) {
    classes = classes.map((className) => (className.startsWith('heading-style-') ? content[node.headingClassProp] : className))
  }
  for (const modifier of modifiers) {
    if (classes.some((className) => familyModifierTargets.get(modifier)?.has(className))) classes.push(modifier)
  }
  const attributes = { ...node.attributes }
  if (classes.length) attributes.class = classes.join(' ')
  if (node.tag === 'img') attributes.src = content[node.prop]
  const attributeText = Object.entries(attributes)
    .map(([name, value]) => ` ${name}="${escapeHtml(value)}"`)
    .join('')
  const indent = '  '.repeat(depth)
  if (node.tag === 'img') return `${indent}<img${attributeText}>\n`
  const inner =
    node.prop && node.tag !== 'img'
      ? escapeHtml(content[node.prop] ?? '')
      : `\n${node.children.map((child) => renderNode(child, content, modifiers, depth + 1)).join('')}${indent}`
  return `${indent}<${node.tag}${attributeText}>${inner}</${node.tag}>\n`
}

const instancesBySection = new Map(plan.instances.map((instance) => [instance.section, instance]))
const resolveContent = (instance) =>
  instance.content.sameAs ? instancesBySection.get(instance.content.sameAs).content : instance.content

// One preview case per variant. Base and is-right render the collection-page
// sequence 03 to 07 together, since the stagger only reads in context.
const collectionSequence = plan.instances.filter((instance) => instance.page === 'happenings-collection')
const previewCases = [
  { id: 'base', label: 'base (happenings-collection 03, 05, 07)', instances: collectionSequence.filter((instance) => instance.variant === 'base') },
  { id: 'is-right', label: 'is-right (happenings-collection 04, 06)', instances: collectionSequence.filter((instance) => instance.variant === 'is-right') },
  { id: 'sequence', label: 'collection page sequence 03 to 07 (base and is-right alternating)', instances: collectionSequence },
  { id: 'is-tall', label: 'is-tall (neighborhood 09)', instances: plan.instances.filter((instance) => instance.variant === 'is-tall') },
]

const renderInstance = (instance) => {
  const modifiers = instance.variant === 'base' ? [] : instance.variant.split(/\s*\+\s*/)
  return plan.tree.map((node) => renderNode(node, resolveContent(instance), modifiers, 2)).join('')
}

const caseMarkup = previewCases
  .map(
    (previewCase) =>
      `  <div class="preview-case" id="case-${previewCase.id}">\n    <p class="preview-label">${escapeHtml(previewCase.label)}</p>\n${previewCase.instances.map(renderInstance).join('')}  </div>\n`,
  )
  .join('')

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Q025 article-card-staggered preview</title>
<link rel="stylesheet" href="preview.css">
</head>
<body>
<!-- Generated by render-preview.mjs from plan.json. Do not edit by hand. -->
${caseMarkup}</body>
</html>
`
writeFileSync(join(planDirectory, 'preview.html'), html)
console.log('Wrote preview.css and preview.html')

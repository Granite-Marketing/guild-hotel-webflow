// Generates preview.css and preview.html from plan.json, validates the plan,
// and (with --shots) takes the Playwright screenshots.
// Usage: node docs/figma/build-plans/Q017/render-preview.mjs [--shots]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const planDirectory = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(planDirectory, '../../../..')
const plan = JSON.parse(fs.readFileSync(path.join(planDirectory, 'plan.json'), 'utf8'))
const breakpoints = [
  ['desktop', null],
  ['tablet', 991],
  ['mobileLandscape', 767],
  ['mobilePortrait', 479],
]

// ---------- validation ----------
const errors = []
const required = ['entry', 'component', 'buildOn', 'reusedClasses', 'familyClasses', 'proposedShared', 'variables', 'tree', 'variants', 'props', 'assets', 'instances', 'openQuestions', 'deviations']
for (const key of required) if (!(key in plan)) errors.push(`missing key ${key}`)
const declared = new Set([
  ...plan.reusedClasses,
  ...plan.familyClasses.map((entry) => entry.name),
  ...plan.proposedShared.map((entry) => entry.name),
])
const usedClasses = new Set()
const walk = (nodes, visit) => nodes.forEach((node) => { visit(node); walk(node.children ?? [], visit) })
walk(plan.tree, (node) => node.classes.forEach((name) => usedClasses.add(name)))
for (const instance of plan.instances) {
  for (const classes of Object.values(instance.classOverrides)) classes.forEach((name) => usedClasses.add(name))
}
for (const name of usedClasses) if (!declared.has(name)) errors.push(`class ${name} is used but not declared`)
for (const variant of plan.variants) {
  if (!variant.modifier) continue
  const combo = plan.familyClasses.find((entry) => entry.name === variant.modifier && entry.comboOn === variant.on)
  if (!combo) errors.push(`variant ${variant.modifier} has no combo class`)
  else if (JSON.stringify(combo.styles) !== JSON.stringify(variant.styleDeltas)) errors.push(`variant ${variant.modifier} styleDeltas differ from its combo class`)
}
const variableNames = new Set(plan.variables)
const styleText = JSON.stringify([plan.familyClasses, plan.proposedShared])
for (const [, name] of styleText.matchAll(/var\(--([a-z0-9-]+)\)/g)) if (!variableNames.has(name)) errors.push(`variable ${name} not listed in variables`)
if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}
console.log(`plan.json valid: ${usedClasses.size} classes used, all declared`)

// ---------- CSS ----------
const declarations = (styles) => Object.entries(styles).map(([property, value]) => `  ${property}: ${value};`).join('\n')
const selectorFor = (entry) => (entry.comboOn ? `.${entry.comboOn}.${entry.name}` : `.${entry.name}`)
const styleSources = [
  ...Object.entries(plan.previewAssumptions.classes).map(([name, value]) => {
    const { comboOn, ...styles } = value
    return { name, comboOn, styles }
  }),
  ...plan.proposedShared,
  ...plan.familyClasses,
]
const cssBlocks = []
cssBlocks.push('/* Generated by render-preview.mjs from plan.json. Do not edit by hand. */')
cssBlocks.push(`:root {\n${declarations(Object.fromEntries(Object.entries(plan.previewAssumptions.variables).map(([name, value]) => [`--${name}`, value])))}\n}`)
for (const [selector, styles] of Object.entries(plan.previewAssumptions.elements)) cssBlocks.push(`${selector} {\n${declarations(styles)}\n}`)
cssBlocks.push(`body {\n${declarations(plan.previewAssumptions.body)}\n}`)
for (const [breakpoint, maxWidth] of breakpoints) {
  const rules = styleSources
    .filter((entry) => entry.styles[breakpoint])
    .map((entry) => `${selectorFor(entry)} {\n${declarations(entry.styles[breakpoint])}\n}`)
  if (!rules.length) continue
  cssBlocks.push(maxWidth ? `@media (max-width: ${maxWidth}px) {\n${rules.join('\n')}\n}` : rules.join('\n'))
}
cssBlocks.push(`/* Preview chrome only (attribute selectors, not part of the plan): cream margins so overlaps show. */
[data-preview] { padding: 8rem 0; }
[data-preview] + [data-preview] { border-top: 1px dashed #b9b29c; }`)
fs.writeFileSync(path.join(planDirectory, 'preview.css'), cssBlocks.join('\n\n') + '\n')

// ---------- HTML ----------
const escapeHtml = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const toRepo = (file) => path.relative(planDirectory, path.join(repoRoot, file))
const textSlots = new Set(['eyebrow', 'heading', 'body-1', 'body-2', 'cta', 'caption'])
const attributesFor = (node) => Object.entries(node.attributes ?? {}).map(([key, value]) => ` ${key}="${escapeHtml(value)}"`).join('')

const renderNode = (node, instance, scope = {}) => {
  if (instance.hidden.includes(node.slot)) return ''
  const classes = instance.classOverrides[node.slot] ?? node.classes
  const classAttribute = classes.length ? ` class="${classes.join(' ')}"` : ''
  if (node.tag === 'img') {
    let source = null
    if (node.slot === 'media-image' && instance.content['media-image']?.local) source = instance.content['media-image'].local
    if (node.slot === 'stamp-image') source = plan.assets.find((asset) => asset.slot === 'stamp-image').local
    if (!source) return ''
    return `<img${classAttribute}${attributesFor(node)} src="${toRepo(source)}">`
  }
  if (node.repeat === 'features') {
    return instance.content.features.map((feature) => renderChildren(node, instance, feature, classAttribute)).join('\n')
  }
  if (node.repeat === 'items') {
    return scope.items.map((item) => `<li${classAttribute}>${escapeHtml(item)}</li>`).join('\n')
  }
  let inner
  if (textSlots.has(node.slot)) inner = escapeHtml(instance.content[node.slot] ?? '')
  else if (node.slot === 'feature-label') inner = escapeHtml(scope.label)
  else inner = (node.children ?? []).map((child) => renderNode(child, instance, scope)).join('\n')
  return `<${node.tag}${classAttribute}${attributesFor(node)}>${inner}</${node.tag}>`
}
const renderChildren = (node, instance, scope, classAttribute) =>
  `<${node.tag}${classAttribute}>${node.children.map((child) => renderNode(child, instance, scope)).join('\n')}</${node.tag}>`

const sections = plan.previewInstances.map(({ variant, section }) => {
  const instance = plan.instances.find((candidate) => candidate.section === section)
  return `<div data-preview="${variant}">\n${plan.tree.map((node) => renderNode(node, instance)).join('\n')}\n</div>`
})
fs.writeFileSync(
  path.join(planDirectory, 'preview.html'),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Q017 split-image-text-light preview</title>
<link rel="stylesheet" href="preview.css">
</head>
<body>
${sections.join('\n')}
</body>
</html>
`,
)
console.log('wrote preview.css and preview.html')

// ---------- screenshots ----------
if (process.argv.includes('--shots')) {
  const { chromium } = await import('@playwright/test')
  const browser = await chromium.launch()
  for (const [width, height] of [[1440, 900], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    await page.goto(`file://${path.join(planDirectory, 'preview.html')}`)
    await page.waitForLoadState('networkidle')
    for (const { variant } of plan.previewInstances) {
      await page.locator(`[data-preview="${variant}"]`).screenshot({ path: path.join(planDirectory, `preview-${variant}-${width}.png`) })
    }
    await page.close()
  }
  await browser.close()
  console.log('wrote screenshots')
}

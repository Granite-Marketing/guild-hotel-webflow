// Generates preview.css and preview.html from plan.json (plus reused-styles.json
// for the Relume utilities the preview cannot load from the live site).
// Usage: node docs/figma/build-plans/Q019/build-preview.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const planDir = dirname(fileURLToPath(import.meta.url))
const plan = JSON.parse(readFileSync(join(planDir, 'plan.json'), 'utf8'))
const reused = JSON.parse(readFileSync(join(planDir, 'reused-styles.json'), 'utf8'))
const repoRoot = '../../../../'

const breakpoints = [
  ['desktop', null],
  ['tablet', 991],
  ['mobileLandscape', 767],
  ['mobilePortrait', 479],
]

const fontValue = (value) => {
  const unquoted = value.replace(/^"|"$/g, '')
  return reused.fontFallbacks[unquoted] ?? value
}

const declarations = (styles) =>
  Object.entries(styles)
    .map(([property, value]) => `  ${property}: ${property === 'font-family' ? fontValue(value) : value};`)
    .join('\n')

// Collect [selector, stylesByBreakpoint] in cascade order: reused, shared, family, variants.
const rules = []
for (const entry of reused.classes) rules.push([`.${entry.name}`, entry.styles])
for (const entry of plan.proposedShared) {
  rules.push([entry.comboOn ? `.${entry.comboOn}.${entry.name}` : `.${entry.name}`, entry.styles])
}
for (const entry of plan.familyClasses) {
  rules.push([entry.comboOn ? `.${entry.comboOn}.${entry.name}` : `.${entry.name}`, entry.styles])
}
for (const variant of plan.variants) rules.push([`.${variant.on}.${variant.modifier}`, variant.styleDeltas])

const rootVariables = Object.entries(reused.variables)
  .map(([name, value]) => `  --${name}: ${name.startsWith('font-') ? fontValue(value) : value};`)
  .join('\n')

let css = `/* Generated by build-preview.mjs from plan.json and reused-styles.json. Do not edit by hand. */\n`
css += `:root {\n${rootVariables}\n}\n`
css += `*, *::before, *::after { box-sizing: border-box; }\n`
css += `body { margin: 0; font-family: var(--font-style-body); background: #fff; }\n`
css += `figure, p { margin: 0; }\n`
css += `.preview-label { font: 12px/1.4 monospace; padding: 8px 16px; background: #111; color: #eee; }\n`
for (const [breakpoint, maxWidth] of breakpoints) {
  const block = rules
    .filter(([, styles]) => styles[breakpoint] && Object.keys(styles[breakpoint]).length)
    .map(([selector, styles]) => `${selector} {\n${declarations(styles[breakpoint])}\n}`)
    .join('\n')
  if (!block) continue
  css += maxWidth ? `@media (max-width: ${maxWidth}px) {\n${block}\n}\n` : `${block}\n`
}
writeFileSync(join(planDir, 'preview.css'), css)

// HTML: render the tree once per variant, using the reference instance's content.
const escapeHtml = (text) =>
  String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

const voidTags = new Set(['img'])

const renderNode = (node, context) => {
  const { content, modifiers, index } = context
  const prop = node.prop?.replace('{n}', index ?? '')
  if (prop?.startsWith('show') && !content[prop]) return ''

  let classes = [...node.classes]
  if (prop === 'heading' && content.headingClasses) classes = [...content.headingClasses]
  for (const variant of plan.variants) {
    if (modifiers.includes(variant.modifier) && classes[0] === variant.on) classes.push(variant.modifier)
  }

  const attributes = { ...node.attributes }
  let inner = ''
  const place = index ? content.places?.[index - 1] : null
  if (prop === 'heading' || prop === 'text') inner = escapeHtml(content[prop])
  if (prop === 'buttonLabel') {
    inner = escapeHtml(content.buttonLabel)
    attributes.href = content.buttonLink
  }
  if (prop?.startsWith('placeName')) inner = escapeHtml(place.name)
  if (prop?.startsWith('placeWalk')) inner = escapeHtml(place.walk)
  if (prop?.startsWith('placeLink')) {
    inner = escapeHtml(place.linkLabel)
    attributes.href = place.link
  }
  if (prop === 'image') {
    attributes.src = repoRoot + content.image
    attributes.alt = content.imageAlt
    attributes.loading = 'eager'
  }

  const renderChildren = (childContext) =>
    node.children.map((child) => renderNode(child, childContext)).join('')

  if (node.repeat) {
    const count = Math.min(node.repeat, content.places?.length ?? node.repeat)
    return Array.from({ length: count }, (_, position) =>
      renderOne(node.tag, classes, attributes, renderChildren({ ...context, index: position + 1 })),
    ).join('')
  }
  return renderOne(node.tag, classes, attributes, inner + renderChildren(context))
}

const renderOne = (tag, classes, attributes, inner) => {
  const attributeText = Object.entries(attributes)
    .map(([name, value]) => ` ${name}="${escapeHtml(value)}"`)
    .join('')
  const open = `<${tag} class="${classes.join(' ')}"${attributeText}>`
  return voidTags.has(tag) ? open : `${open}${inner}</${tag}>`
}

const referenceInstances = plan.instances.filter((instance) => !instance.content.sameAs)
const sections = referenceInstances
  .map((instance) => {
    const modifiers = instance.variant === 'base' ? [] : instance.variant.split(' + ')
    const variantId = instance.variant === 'base' ? 'base' : modifiers.join('-')
    const body = plan.tree.map((node) => renderNode(node, { content: instance.content, modifiers })).join('')
    return `<div class="preview-label">${escapeHtml(`${instance.variant}: ${instance.section}`)}</div>\n<div id="variant-${variantId}">${body}</div>`
  })
  .join('\n')

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Q019 map-feature preview</title>
<link rel="stylesheet" href="preview.css">
</head>
<body>
${sections}
</body>
</html>
`
writeFileSync(join(planDir, 'preview.html'), html)
console.log(`Wrote preview.css and preview.html (${referenceInstances.length} variants)`)

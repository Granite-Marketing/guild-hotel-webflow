// Generates preview.css and preview.html from plan.json, then checks that
// every class used in the tree and the preview is declared in the plan.
// Run: node docs/figma/build-plans/Q022/gen-preview.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = path.dirname(fileURLToPath(import.meta.url))
const plan = JSON.parse(fs.readFileSync(path.join(directory, 'plan.json'), 'utf8'))

const breakpoints = {
  desktop: null,
  tablet: '(max-width: 991px)',
  mobileLandscape: '(max-width: 767px)',
  mobilePortrait: '(max-width: 479px)',
}

// Reused utilities, typography, buttons and variables come from ../shared-preview.css.

const selectorFor = (entry) => (entry.comboOn ? `.${entry.comboOn}.${entry.name}` : `.${entry.name}`)

const rule = (selector, declarations) => {
  const lines = Object.entries(declarations).map(([property, value]) => `  ${property}: ${value};`)
  return lines.length ? `${selector} {\n${lines.join('\n')}\n}` : ''
}

const blocksByBreakpoint = Object.fromEntries(Object.keys(breakpoints).map((name) => [name, []]))
const addEntry = (entry) => {
  const selector = selectorFor(entry)
  for (const [breakpoint, declarations] of Object.entries(entry.styles || {})) {
    const css = rule(selector, declarations)
    if (css) blocksByBreakpoint[breakpoint].push(css)
  }
  for (const [state, declarations] of Object.entries(entry.states || {})) {
    const pseudo = state === 'placeholder' ? '::placeholder' : `:${state}`
    blocksByBreakpoint.desktop.push(rule(`${selector}${pseudo}`, declarations))
  }
}

plan.familyClasses.forEach(addEntry)
for (const variant of plan.variants) {
  if (!variant.modifier) continue
  addEntry({ name: variant.modifier, comboOn: variant.on, styles: variant.styleDeltas })
}

let css = `/* Generated by gen-preview.mjs from plan.json. Do not edit by hand. */\n`
// The brand fonts are not available locally; alias them to the closest macOS
// faces so the preview reads like the design. Preview only.
css += `@font-face { font-family: Morello; src: local("Snell Roundhand"), local("SnellRoundhand"); }\n`
css += `@font-face { font-family: "Sackers Heavy Gothic"; src: local("Copperplate"), local("Copperplate-Bold"); }\n`
css += `@font-face { font-family: "Gatch Test"; src: local("Avenir Next"), local("AvenirNext-Regular"); }\n`
css += `*, *::before, *::after { box-sizing: border-box; }\n`
css += `body { margin: 0; font-family: var(--_typography---font-styles--body); color: var(--_primitives---colors--neutral-darkest); background: #fff; }\n`
css += `h1, h2, h3, p, figure { margin: 0; }\n`
css += `.preview-label { font: 12px/1.4 ui-monospace, monospace; padding: 8px 16px; background: #111; color: #eee; }\n\n`
for (const [breakpoint, query] of Object.entries(breakpoints)) {
  const body = blocksByBreakpoint[breakpoint].join('\n\n')
  if (!body) continue
  css += query ? `@media ${query} {\n${body.replace(/^/gm, '  ')}\n}\n\n` : `${body}\n\n`
}
fs.writeFileSync(path.join(directory, 'preview.css'), css)

// HTML, rendered from instance content using the tree's classes.
const escape = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')

const renderField = (field) => {
  const fieldClasses = ['form-split-script-contact_field', ...(field.full ? ['is-full'] : [])].join(' ')
  const control =
    field.type === 'textarea'
      ? `<textarea class="form-split-script-contact_input is-textarea" name="${field.name}" placeholder="${escape(field.label)}" aria-label="${escape(field.label)}"></textarea>`
      : `<input class="form-split-script-contact_input" type="${field.type}" name="${field.name}" placeholder="${escape(field.label)}" aria-label="${escape(field.label)}">`
  return `<div class="${fieldClasses}">${control}</div>`
}

const renderForm = (content, sectionId) => {
  const fieldsets = content.fieldsets
    .map((fieldset) => {
      const headingId = `${sectionId}-${slug(fieldset.heading)}-heading`
      return `<div class="form-split-script-contact_fieldset" role="group" aria-labelledby="${headingId}">
            <header class="form-split-script-contact_fieldset-header"><h3 class="heading-style-h4" id="${headingId}">${escape(fieldset.heading)}</h3></header>
            <div class="form-split-script-contact_fields">${fieldset.fields.map(renderField).join('')}</div>
          </div>`
    })
    .join('\n')
  const formBlockClasses = ['form-split-script-contact_form-block', ...(content.formModifier ? [content.formModifier] : [])].join(' ')
  return `<div class="${formBlockClasses}">
        <form class="form-split-script-contact_form" name="${escape(content.formName)}" onsubmit="return false">
          <div class="form-split-script-contact_fieldsets">${fieldsets}</div>
          <footer class="form-split-script-contact_footer"><input class="button is-chamfer is-dark" type="submit" value="${escape(content.submit)}"></footer>
        </form>
        <div class="form-split-script-contact_message" hidden>Thank you. Your request has been received.</div>
        <div class="form-split-script-contact_message" hidden>Something went wrong. Please try again.</div>
      </div>`
}

const renderInstance = (instance, id) => {
  const content = instance.content
  const isScript = content.headingStyle === 'script'
  const headingTag = content.headingTag || 'h2'
  const headingClasses = isScript ? 'text-style-script' : 'heading-style-h2'
  const headerClasses = ['form-split-script-contact_header', ...(isScript ? ['is-rotated'] : [])].join(' ')
  const contentClasses = ['form-split-script-contact_content', ...(content.contentModifier ? [content.contentModifier] : [])].join(' ')
  const sectionClasses = ['section_form-split-script-contact', ...(instance.variant !== 'base' ? [instance.variant] : [])].join(' ')
  const paragraph = content.paragraph
    ? `<div class="form-split-script-contact_paragraph text-size-medium"><p>${escape(content.paragraph)}</p></div>`
    : ''
  const details = content.details
    ? `<div class="form-split-script-contact_details">${content.details
        .map((detail) => {
          const value = escape(detail.value).replace(/\n/g, '<br>')
          return `<div class="form-split-script-contact_detail"><div class="form-split-script-contact_detail-label text-style-caps-caption-16">${escape(detail.label)}</div><div class="form-split-script-contact_detail-value text-size-medium"><p>${value}</p></div></div>`
        })
        .join('')}</div>`
    : ''
  const links = content.links
    ? `<div class="form-split-script-contact_links">${content.links
        .map((link) => `<a class="form-split-script-contact_link text-style-caps-caption-16" href="#" target="_blank" rel="noopener">${escape(link.label)}</a>`)
        .join('')}</div>`
    : ''
  const rightColumn = content.fieldsets ? renderForm(content, id) : `<figure class="form-split-script-contact_media"></figure>`
  return `<div class="preview-label">${instance.section} (${instance.variant})</div>
<section class="${sectionClasses}" id="${id}">
  <div class="padding-global padding-section-large">
    <div class="container-large">
      <article class="form-split-script-contact_component">
        <div class="${contentClasses}">
          <header class="${headerClasses}"><${headingTag} class="${headingClasses}">${escape(content.heading)}</${headingTag}></header>
          ${paragraph}
          ${details}
          ${links}
        </div>
        ${rightColumn}
      </article>
    </div>
  </div>
</section>`
}

export const previewTargets = []
const sections = plan.instances
  .filter((instance) => !instance.content.sameAs)
  .map((instance) => {
    const page = instance.page
    const variant = plan.variants.find((entry) => (entry.modifier ?? entry.name) === instance.variant)
    const isReference = variant.crop.includes(`/${instance.section.split('/')[1]}/`)
    const id = isReference ? instance.variant : `${instance.variant}-${page}`
    const crop = `figma/pages/${page}/sections/${instance.section.split('/')[1]}/section.webp`
    previewTargets.push({ id, variant: instance.variant, crop, section: instance.section })
    return renderInstance(instance, id)
  })

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Q022 form-split-script-contact preview</title>
<link rel="stylesheet" href="../shared-preview.css">
<link rel="stylesheet" href="preview.css">
</head>
<body>
${sections.join('\n\n')}
</body>
</html>
`
fs.writeFileSync(path.join(directory, 'preview.html'), html)
fs.writeFileSync(path.join(directory, 'preview-targets.json'), JSON.stringify(previewTargets, null, 2) + '\n')

// Class check: tree and preview may only use declared classes.
const declared = new Set([
  ...plan.reusedClasses,
  ...plan.familyClasses.map((entry) => entry.name),
  ...plan.proposedShared.map((entry) => entry.name),
  ...plan.variants.filter((variant) => variant.modifier).map((variant) => variant.modifier),
])
const treeClasses = new Set()
const walk = (node) => {
  for (const key of ['classes', 'optionalClasses', 'altClasses']) (node[key] || []).forEach((name) => treeClasses.add(name))
  ;(node.children || []).forEach(walk)
}
plan.tree.forEach(walk)
const htmlClasses = new Set([...html.matchAll(/class="([^"]+)"/g)].flatMap((match) => match[1].split(/\s+/)))
htmlClasses.delete('preview-label')
const missing = [...treeClasses, ...htmlClasses].filter((name) => !declared.has(name))
const unused = [...declared].filter((name) => !treeClasses.has(name))
if (missing.length) {
  console.error('Undeclared classes:', [...new Set(missing)].join(', '))
  process.exit(1)
}
if (unused.length) console.log('Declared but not in tree (variant modifiers are expected):', unused.join(', '))
console.log(`OK: ${treeClasses.size} tree classes, ${htmlClasses.size} preview classes, all declared. ${previewTargets.length} sections rendered.`)

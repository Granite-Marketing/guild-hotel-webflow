// Generates preview.css and preview.html for Q015 from plan.json.
// Only family classes are emitted here. Live reused classes, K01 shared
// classes and the :root variables come from ../shared-preview.css.
// Run: node docs/figma/build-plans/Q015/generate-preview.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const planDirectory = dirname(fileURLToPath(import.meta.url))
const plan = JSON.parse(readFileSync(join(planDirectory, 'plan.json'), 'utf8'))

const mediaQueries = {
  desktop: null,
  tablet: '(max-width: 991px)',
  mobileLandscape: '(max-width: 767px)',
  mobilePortrait: '(max-width: 479px)',
}

const rule = (selector, declarations) => {
  const body = Object.entries(declarations)
    .map(([property, value]) => `  ${property}: ${value};`)
    .join('\n')
  return `${selector} {\n${body}\n}`
}

const classEntries = [
  ...plan.familyClasses,
]

const blocks = { desktop: [], tablet: [], mobileLandscape: [], mobilePortrait: [] }
for (const entry of classEntries) {
  for (const [breakpoint, declarations] of Object.entries(entry.styles)) {
    if (Object.keys(declarations).length) blocks[breakpoint].push(rule(`.${entry.name}`, declarations))
  }
  for (const [parentSelector, declarations] of Object.entries(entry.states ?? {})) {
    blocks.desktop.push(rule(`.${parentSelector.replace(/ /g, '.')} .${entry.name}`, declarations))
  }
}
for (const variant of plan.variants.filter((item) => item.modifier)) {
  for (const [breakpoint, declarations] of Object.entries(variant.styleDeltas)) {
    blocks[breakpoint].push(rule(`.${variant.on}.${variant.modifier}`, declarations))
  }
}

const css = [
  '/* Generated by generate-preview.mjs from plan.json. Do not edit by hand. */',
  '*, *::before, *::after { box-sizing: border-box; }',
  'body { margin: 0; background: #ffffff; font-family: var(--_typography---font-styles--body); -webkit-font-smoothing: antialiased; }',
  'p { margin: 0; }',
  '.preview-label { font: 12px/1.4 ui-monospace, monospace; padding: 8px 16px; background: #222; color: #fff; margin: 0 0 8px; }',
  ...blocks.desktop,
  ...Object.entries(mediaQueries)
    .filter(([breakpoint, query]) => query && blocks[breakpoint].length)
    .map(([breakpoint, query]) => `@media ${query} {\n${blocks[breakpoint].join('\n')}\n}`),
].join('\n\n')

const escapeHtml = (value) => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

const placeholderAnswer = plan.content.items[0].answer

// Renders a tree node. The repeated accordion item takes its question and
// answer from plan.content; the first item is shown open, as in the crop,
// with the inline state the accordion module writes (is-active, aria-expanded,
// max-height on the content wrapper).
const render = (node, context = {}) => {
  if (node.repeat) {
    return plan.content.items
      .map((item, index) => render({ ...node, repeat: undefined }, { item, index }))
      .join('')
  }
  if (node.tag === 'embed') return node.html
  const attributes = { ...node.attributes }
  const classes = [...node.classes]
  const isOpen = context.index === 0
  if (classes.includes('accordion_header')) {
    attributes['aria-expanded'] = String(isOpen)
    attributes.id = `accordion-${context.index}`
    attributes['aria-controls'] = `accordion-target-${context.index}`
    if (isOpen) classes.push('is-active')
  }
  if (classes.includes('accordion_content-wrapper')) {
    attributes.id = `accordion-target-${context.index}`
    attributes['aria-labelledby'] = `accordion-${context.index}`
    if (!isOpen) attributes.style = 'max-height: 0px'
  }
  if (classes.length) attributes.class = classes.join(' ')
  const attributeString = Object.entries(attributes)
    .map(([name, value]) => ` ${name}="${escapeHtml(value)}"`)
    .join('')
  let text = node.text ?? ''
  if (context.item) {
    text = text.replace('{question}', context.item.question).replace('{answer}', context.item.answer ?? placeholderAnswer)
  }
  const children = node.children.map((child) => render(child, context)).join('')
  return `<${node.tag}${attributeString}>${escapeHtml(text)}${children}</${node.tag}>`
}

const sections = plan.variants
  .map((variant) => {
    const tree = structuredClone(plan.tree[0])
    if (variant.modifier) tree.classes.push(variant.modifier)
    const label = `${plan.component} / ${variant.modifier ?? 'base'} (reference: ${variant.crop})`
    return `<p class="preview-label" data-preview-label>${escapeHtml(label)}</p>\n<div data-variant="${variant.modifier ?? 'base'}">${render(tree)}</div>`
  })
  .join('\n')

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${plan.entry} ${plan.component} preview</title>
<link rel="stylesheet" href="../shared-preview.css">\n<link rel="stylesheet" href="preview.css">
</head>
<body>
${sections}
</body>
</html>
`

writeFileSync(join(planDirectory, 'preview.css'), `${css}\n`)
writeFileSync(join(planDirectory, 'preview.html'), html)
console.log('Wrote preview.css and preview.html')

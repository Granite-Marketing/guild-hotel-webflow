// Generates preview.css (family and variant rules only; reused and shared classes come from ../shared-preview.css) from plan.json, validates the plan's class coverage,
// and screenshots every variant section in preview.html at 1440 and 390.
// Usage: node docs/figma/build-plans/Q020/generate-preview.mjs [--shots]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const planDir = dirname(fileURLToPath(import.meta.url))
const plan = JSON.parse(readFileSync(join(planDir, 'plan.json'), 'utf8'))

const breakpointQueries = {
  desktop: null,
  tablet: '(max-width: 991px)',
  mobileLandscape: '(max-width: 767px)',
  mobilePortrait: '(max-width: 479px)',
}

// Nested rich text styling is set by hand in the Designer (MCP limitation).
const richTextNested = `.text-rich-text p { margin: 0; }
.text-rich-text ul { margin: 0; padding-left: 1.75rem; }
.text-rich-text li { margin: 0; }`

const declarations = (styles) =>
  Object.entries(styles).map(([property, value]) => `  ${property}: ${value};`).join('\n')

const rulesByBreakpoint = Object.fromEntries(Object.keys(breakpointQueries).map((bp) => [bp, []]))
const addRule = (breakpoint, selector, styles) => {
  if (styles && Object.keys(styles).length) rulesByBreakpoint[breakpoint].push(`${selector} {\n${declarations(styles)}\n}`)
}

for (const entry of [...plan.familyClasses, ...plan.proposedShared]) {
  for (const [bp, values] of Object.entries(entry.styles)) addRule(bp, `.${entry.name}`, values)
}
for (const variant of plan.variants) {
  if (!variant.modifier || variant.modifier === 'base') continue
  const modifierSelector = variant.modifier.split(' ').map((m) => `.${m}`).join('')
  for (const [bp, byClass] of Object.entries(variant.styleDeltas)) {
    for (const [className, values] of Object.entries(byClass)) {
      const selector = className === variant.on
        ? `.${variant.on}${modifierSelector}`
        : `.${variant.on}${modifierSelector} .${className}`
      addRule(bp, selector, values)
    }
  }
}

const css = [
  '/* Generated by generate-preview.mjs from plan.json. Do not edit by hand. */',
  '*, *::before, *::after { box-sizing: border-box; }',
  'body { margin: 0; background: var(--_primitives---colors--neutral-lightest); color: var(--_primitives---colors--neutral-darkest); font-family: var(--_typography---font-styles--body); }',
  'h2, h3, p, figure { font-weight: 400; }',
  richTextNested,
  ...Object.entries(rulesByBreakpoint).map(([bp, rules]) =>
    breakpointQueries[bp] ? `@media ${breakpointQueries[bp]} {\n${rules.join('\n')}\n}` : rules.join('\n')),
].join('\n\n')
writeFileSync(join(planDir, 'preview.css'), css + '\n')

// Validation: every class in the tree and in preview.html is declared in the plan.
const declared = new Set([
  ...plan.reusedClasses,
  ...plan.familyClasses.map((c) => c.name),
  ...plan.proposedShared.map((c) => c.name),
  ...plan.variants.flatMap((v) => (!v.modifier || v.modifier === 'base' ? [] : v.modifier.split(' '))),
])
const treeClasses = []
const walk = (nodes) => nodes.forEach((node) => { treeClasses.push(...node.classes); walk(node.children ?? []) })
walk(plan.tree)
const html = readFileSync(join(planDir, 'preview.html'), 'utf8')
const htmlClasses = [...html.matchAll(/class="([^"]+)"/g)].flatMap((match) => match[1].split(/\s+/))
const undeclared = [...new Set([...treeClasses, ...htmlClasses])].filter((name) => !declared.has(name))
const required = ['entry', 'component', 'buildOn', 'reusedClasses', 'familyClasses', 'proposedShared', 'variables', 'tree', 'variants', 'props', 'assets', 'instances', 'openQuestions', 'deviations']
const missingKeys = required.filter((key) => !(key in plan))
if (undeclared.length || missingKeys.length) {
  console.error('Undeclared classes:', undeclared, 'Missing keys:', missingKeys)
  process.exit(1)
}
console.log(`preview.css written; ${declared.size} declared classes, all tree and preview classes covered`)

if (process.argv.includes('--shots')) {
  const { chromium } = await import('@playwright/test')
  const browser = await chromium.launch()
  const variantIds = [...html.matchAll(/<section id="([^"]+)"/g)].map((match) => match[1])
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } })
    await page.goto(pathToFileURL(join(planDir, 'preview.html')).href)
    await page.waitForLoadState('networkidle')
    for (const id of variantIds) {
      await page.locator(`#${id}`).screenshot({ path: join(planDir, `preview-${id}-${width}.png`) })
    }
    await page.close()
  }
  await browser.close()
  console.log('screenshots:', variantIds.join(', '))
}

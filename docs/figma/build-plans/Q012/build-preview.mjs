// Renders preview.html and preview.css from plan.json, then screenshots them.
// Usage: node docs/figma/build-plans/Q012/build-preview.mjs [--no-shots]
// CSS comes only from plan.json style values. Reused Relume classes have no
// values in the plan, so their stand-ins come from figma/tokens.json and
// docs/reference/breakpoints.md (Q001 sets the live values).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const planDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(planDir, '../../../..')
const plan = JSON.parse(readFileSync(join(planDir, 'plan.json'), 'utf8'))
const tokens = JSON.parse(readFileSync(join(repoRoot, 'figma/tokens.json'), 'utf8'))
const toRepo = relative(planDir, repoRoot)

const breakpoints = {
  desktop: null,
  tablet: '(max-width: 991px)',
  mobileLandscape: '(max-width: 767px)',
  mobilePortrait: '(max-width: 479px)',
}

// Variables: hex from the tokens mapping, plus D01 (#4A1217 gets its own variable).
const colorByVariable = Object.fromEntries(
  tokens.mapping.colors.filter((color) => color.target).map((color) => [color.target, color.hex]),
)
colorByVariable['color-brand-4a1217'] = '#4A1217'
const fontByVariable = Object.fromEntries(
  tokens.mapping.fontVariables.map((font) => [font.variable, font.value]),
)
// Local fallbacks: the brand fonts are not available offline.
const fontFallbacks = {
  'Sackers Heavy Gothic': "'Sackers Heavy Gothic', Copperplate, 'Copperplate Gothic', serif",
  'Gatch Test': "'Gatch Test', Georgia, serif",
  Morello: "Morello, 'Snell Roundhand', 'Apple Chancery', cursive",
}
const rootVariables = plan.variables.map((name) => {
  if (colorByVariable[name]) return `  --${name}: ${colorByVariable[name]};`
  if (fontByVariable[name]) return `  --${name}: ${fontFallbacks[fontByVariable[name]]};`
  throw new Error(`No value for variable ${name}`)
})

// Stand-ins for reused classes.
const morello = tokens.mapping.typography.find((entry) => entry.source.key === 'Morello|400|60|72|0|ORIGINAL').classValues
const reusedStandIns = {
  'padding-global': { desktop: { 'padding-left': '2rem', 'padding-right': '2rem' } },
  'padding-section-large': {
    desktop: { 'padding-top': '7rem', 'padding-bottom': '7rem' },
    tablet: { 'padding-top': '5rem', 'padding-bottom': '5rem' },
    mobileLandscape: { 'padding-top': '3.5rem', 'padding-bottom': '3.5rem' },
    mobilePortrait: { 'padding-top': '2.5rem', 'padding-bottom': '2.5rem' },
  },
  'heading-style-h1': {
    desktop: {
      'font-family': fontFallbacks[morello.fontFamily],
      'font-size': `${morello.fontSizeRem}rem`,
      'line-height': String(morello.lineHeight),
      'letter-spacing': `${morello.letterSpacingEm}em`,
      margin: '0',
    },
    tablet: { 'font-size': '3rem' },
    mobilePortrait: { 'font-size': '2.5rem' },
  },
  'text-weight-normal': { desktop: { 'font-weight': '400' } },
  button: { desktop: { display: 'inline-block' } },
  'w-form-done': { desktop: { display: 'none' } },
  'w-form-fail': { desktop: { display: 'none' } },
}

const declarations = (styles) =>
  Object.entries(styles)
    .filter(([, value]) => typeof value === 'string')
    .map(([property, value]) => `  ${property}: ${value};`)
    .join('\n')

const rules = { desktop: [], tablet: [], mobileLandscape: [], mobilePortrait: [] }
const addRule = (selector, stylesByBreakpoint) => {
  for (const breakpoint of Object.keys(breakpoints)) {
    const styles = stylesByBreakpoint[breakpoint] ?? {}
    const body = declarations(styles)
    if (body) rules[breakpoint].push(`${selector} {\n${body}\n}`)
    for (const [state, stateStyles] of Object.entries(styles)) {
      if (typeof stateStyles === 'object') rules[breakpoint].push(`${selector}${state} {\n${declarations(stateStyles)}\n}`)
    }
  }
}

for (const name of plan.reusedClasses) {
  if (!reusedStandIns[name]) throw new Error(`No stand-in for reused class ${name}`)
  addRule(`.${name}`, reusedStandIns[name])
}
for (const shared of plan.proposedShared) {
  const base = shared.on ? shared.on.split(' ').map((name) => `.${name}`).join('') : ''
  addRule(`${base}.${shared.name}`, shared.styles)
}
for (const familyClass of plan.familyClasses) addRule(`.${familyClass.name}`, familyClass.styles)

const css = [
  '/* Generated by build-preview.mjs from plan.json. Do not edit by hand. */',
  `:root {\n${rootVariables.join('\n')}\n}`,
  '*, *::before, *::after { box-sizing: border-box; }',
  'body { margin: 0; background: #111; }',
  'p { margin: 0; }',
  'h2 { font-weight: inherit; }',
  ...rules.desktop,
  ...['tablet', 'mobileLandscape', 'mobilePortrait'].map(
    (breakpoint) => `@media ${breakpoints[breakpoint]} {\n${rules[breakpoint].join('\n')}\n}`,
  ),
].join('\n\n')

// Tree to HTML.
const knownClasses = new Set([
  ...plan.reusedClasses,
  ...plan.familyClasses.map((familyClass) => familyClass.name),
  ...plan.proposedShared.map((shared) => shared.name),
])
const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')
const voidTags = new Set(['img', 'input'])
const render = (node, depth = 0) => {
  for (const name of node.classes) {
    if (!knownClasses.has(name)) throw new Error(`Class ${name} is not declared in plan.json`)
  }
  const pad = '  '.repeat(depth)
  const attributes = { ...node.attributes }
  if (attributes.src && !attributes.src.startsWith('http')) attributes.src = `${toRepo}/${attributes.src}`
  const attributeText = [
    node.classes.length ? `class="${node.classes.join(' ')}"` : '',
    ...Object.entries(attributes).map(([key, value]) => (value === '' ? key : `${key}="${escape(value)}"`)),
  ].filter(Boolean).join(' ')
  const open = `<${node.tag}${attributeText ? ' ' + attributeText : ''}>`
  if (voidTags.has(node.tag)) return `${pad}${open}`
  const inner = [node.text ? `${pad}  ${escape(node.text)}` : '', ...node.children.map((child) => render(child, depth + 1))]
    .filter(Boolean).join('\n')
  return inner ? `${pad}${open}\n${inner}\n${pad}</${node.tag}>` : `${pad}${open}</${node.tag}>`
}

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${plan.entry} ${plan.component} preview</title>
<link rel="stylesheet" href="preview.css">
</head>
<body>
<!-- Generated by build-preview.mjs from plan.json. Variant: base (the only variant). -->
${plan.tree.map((node) => render(node)).join('\n')}
</body>
</html>
`

writeFileSync(join(planDir, 'preview.css'), css + '\n')
writeFileSync(join(planDir, 'preview.html'), html)
console.log('wrote preview.html and preview.css')

if (!process.argv.includes('--no-shots')) {
  const { chromium } = await import('@playwright/test')
  const browser = await chromium.launch()
  const variants = ['base', ...plan.variants.map((variant) => variant.modifier)]
  for (const variant of variants) {
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 900 } })
      await page.goto(`file://${join(planDir, 'preview.html')}`)
      await page.waitForLoadState('networkidle')
      await page.evaluate(() => Promise.all([...document.images].map((image) => image.decode().catch(() => {}))))
      const section = page.locator('section').first()
      await section.screenshot({ path: join(planDir, `preview-${variant}-${width}.png`) })
      console.log(`shot preview-${variant}-${width}.png`)
      await page.close()
    }
  }
  await browser.close()
}
